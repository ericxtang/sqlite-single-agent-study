p=subprocess.Popen(['target/release/sqlite-agent'],stdin=subprocess.PIPE,stdout=subprocess.PIPE,text=True)
def request(**req):
 p.stdin.write(json.dumps(req)+'\n');p.stdin.flush();return json.loads(p.stdout.readline())
def sql(s,expected=None,columns=None,error=False):
 r=request(op='execute',sql=s)
 if error:
  assert not r['ok'],(s,r)
 else:
  assert r['ok'],(s,r)
  vals=[[None if v['type']=='null' else int(v['value']) if v['type']=='integer' else float(v['value']) if v['type']=='real' else v['value'] for v in row] for row in r['rows']]
  if expected is not None:assert vals==expected,(s,vals,expected)
  if columns is not None:assert r['columns']==columns,(s,r['columns'],columns)
 return r
